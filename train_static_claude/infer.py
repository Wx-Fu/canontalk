"""Single-image inference: one portrait -> renders on a yaw/pitch orbit.

The image is center-cropped to a square around the head and resized to the
encoder size. Without calibration, intrinsics are assumed (``--fov``); the
predicted head pose then lives in that assumed camera. Views are generated by
rotating the head frame about its origin: Q_view = (R_hat R(yaw, pitch), t_hat).
``--driver`` takes the dynamics code e (expression / mouth) from another
image of the same person while keeping the identity slots of ``--image``.

  python -m train_static_claude.infer --checkpoint RUN/step_0150000.pt \
      --image face.png --out orbit.png [--prior RUNB/prior_0060000.pt --seed 0]
"""
import argparse
import math
from pathlib import Path

import numpy as np
import torch
from PIL import Image

from .train import build_from_checkpoint


def load_square(path, size):
    img = Image.open(path).convert("RGB")
    w, h = img.size
    side = min(w, h)
    img = img.crop(((w - side) // 2, (h - side) // 2, (w - side) // 2 + side,
                    (h - side) // 2 + side)).resize((size, size), Image.Resampling.LANCZOS)
    return torch.from_numpy(np.asarray(img).astype(np.float32) / 255).permute(2, 0, 1)[None]


def intrinsics(size, fov_deg):
    f = size / 2 / math.tan(math.radians(fov_deg) / 2)
    return torch.tensor([[[f, 0, size / 2], [0, f, size / 2], [0, 0, 1.]]])


def head_rotation(yaw, pitch):
    y, p = math.radians(yaw), math.radians(pitch)
    ry = torch.tensor([[math.cos(y), 0, math.sin(y)], [0, 1, 0], [-math.sin(y), 0, math.cos(y)]])
    rx = torch.tensor([[1, 0, 0], [0, math.cos(p), -math.sin(p)], [0, math.sin(p), math.cos(p)]])
    return (ry @ rx)[None]


@torch.no_grad()
def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--checkpoint", type=Path, required=True)
    p.add_argument("--prior", type=Path, default=None)
    p.add_argument("--image", type=Path, required=True)
    p.add_argument("--driver", type=Path, default=None)
    p.add_argument("--fov", type=float, default=12.0, help="assumed full field of view (deg)")
    p.add_argument("--yaws", type=float, nargs="+", default=[-75, -50, -25, 0, 25, 50, 75])
    p.add_argument("--pitches", type=float, nargs="+", default=[-20, 0, 20])
    p.add_argument("--guidance", type=float, default=1.5)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--device", default="cuda")
    args = p.parse_args(argv)
    device = torch.device(args.device)
    net, saved = build_from_checkpoint(args.checkpoint, device)
    size, rsize = saved.enc_size, saved.render_size
    k = intrinsics(size, args.fov).to(device)
    prep = lambda x: x
    if not getattr(saved, "keep_source_background", False):
        from .losses import Masker, neutral_background
        masker = Masker().to(device)
        prep = lambda x: neutral_background(masker, x)
    image = prep(load_square(args.image, size).to(device))
    s = net.encoder(image, k)
    z_id = s
    if args.prior:
        from .prior import SlotPrior
        ck = torch.load(args.prior, map_location="cpu", weights_only=False)
        prior = SlotPrior(**ck["prior_kwargs"]).to(device).eval()
        prior.load_state_dict(ck["prior"])
        g = torch.Generator(device=device).manual_seed(args.seed)
        z_id = prior.sample(s, net.encoder.slot_embed, guidance=args.guidance, generator=g)
    e = s["e"]
    if args.driver:
        e = net.encoder(prep(load_square(args.driver, size).to(device)), k)["e"]
    z = net.encoder.compose(z_id, e)
    k_r = intrinsics(rsize, args.fov).to(device)
    rows = []
    for pitch in args.pitches:
        tiles = []
        for yaw in args.yaws:
            r = s["R"] @ head_rotation(yaw, pitch).to(device)
            out = net.decoder(z, r, s["t"], k_r)
            rgb = out["rgb"] * out["alpha"] + (1 - out["alpha"])
            tiles.append(rgb[0])
        rows.append(torch.cat(tiles, -1))
    src = torch.nn.functional.interpolate(image, size=(rsize, rsize), mode="bilinear",
                                          align_corners=False)[0]
    grid = torch.cat(rows, -2)
    pad = torch.ones(3, grid.shape[1], rsize, device=device)
    pad[:, :rsize] = src
    grid = torch.cat((pad, grid), -1).clamp(0, 1).permute(1, 2, 0).cpu().numpy()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray((grid * 255).astype(np.uint8)).save(args.out)
    print(f"saved {args.out}: rows pitch={args.pitches}, cols yaw={args.yaws}")


if __name__ == "__main__":
    main()
